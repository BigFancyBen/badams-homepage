/**
 * Structured data for crawlers, rendered into the server HTML. `<` is escaped
 * so that no string in the payload can close the script tag.
 */
export function JsonLd({ data }: { data: object }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data).replace(/</g, "\\u003c") }}
    />
  );
}
